def lookup_principles(improving: int, worsening: int) -> list[int]:
    """Return inventive principles for a contradiction pair. Pure deterministic code."""
    if not (1 <= improving <= 39):
        raise ValueError(f"improving must be 1-39, got {improving}")
    if not (1 <= worsening <= 39):
        raise ValueError(f"worsening must be 1-39, got {worsening}")
    if improving == worsening:
        return []
    return MATRIX.get(improving, {}).get(worsening, [])


def get_parameter_name(n: int) -> str:
    return PARAMETERS.get(n, f"Parameter {n}")


def get_principle_name(n: int) -> str:
    return PRINCIPLES.get(n, f"Principle {n}")


def get_principle_description(n: int) -> dict[str, str]:
    return {"number": str(n), "name": get_principle_name(n)}
